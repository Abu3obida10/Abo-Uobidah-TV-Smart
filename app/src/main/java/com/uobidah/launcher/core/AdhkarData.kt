    fun list(morning: Boolean): List<Dhikr> = if (morning) this.morning else this.evening

    /** قبل الساعة 15:00 → أذكار الصباح، وإلا المساء. */
    fun isMorningHour(hour: Int): Boolean = hour in 0..14

    /** يحوّل رقماً إلى أرقام عربية-هندية. */
    fun arabicDigits(n: Int): String =
        n.toString().map { if (it in '0'..'9') '٠' + (it - '0') else it }.joinToString("")

    /** عدّادات محفوظة كنص "1,0,3": تُستعاد بحذر وتُقصّ/تُملأ لتطابق طول القائمة. */
    fun decodeCounts(saved: String?, size: Int): IntArray {
        val out = IntArray(size)
        if (saved.isNullOrBlank()) return out
        val parts = saved.split(',')
        for (i in 0 until minOf(size, parts.size)) out[i] = parts[i].trim().toIntOrNull()?.coerceAtLeast(0) ?: 0
        return out
    }

    fun encodeCounts(c: IntArray): String = c.joinToString(",")
